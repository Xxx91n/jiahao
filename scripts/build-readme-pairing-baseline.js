#!/usr/bin/env node
'use strict';
// scripts/build-readme-pairing-baseline.js - ADR-0092 D-P2 (grill-t35 D-006):
// generator for the committed README/zh-CN pairing baseline. The baseline is
// the ratchet (industry-standard baseline/ratchet shape): it enumerates the
// real unpaired README-touching commits on the published line so the leg can
// tell historical backlog apart from NEW drift.
//
// Ratchet discipline (the anti-laundering clause):
//   --write  regenerates the entry list from the live scan (deliberate act,
//           every diff is a human look at newly registered violations)
//   --check  reconciles committed-vs-live and fails on ANY divergence
// Hand-added entries are not special: --check re-derives every one of them,
// so an entry that is not a real violation fails as stale. There is no prose
// waiver channel that can silently absorb a violation.
//
// Usage: node scripts/build-readme-pairing-baseline.js [--write|--check]

const fs = require('fs');
const path = require('path');
const { requireCapabilities } = require('../src/shared/capability');
const pairing = require('./shared/readme-pairing');

const ROOT = path.join(__dirname, '..');
const OUT_REL = pairing.BASELINE_REL;

function build(root, opts) {
  const o = opts || {};
  const live = pairing.scanViolations(root, { tip: o.tip || 'HEAD' });
  return {
    schema_version: 1,
    _doc: 'ADR-0092 D-P2 (grill-t35 D-006): the README/zh-CN same-commit pairing baseline - a committed, monotonically-shrinking ratchet. Generated by scripts/build-readme-pairing-baseline.js; hand-edit forbidden. Each entry is a real commit on the published line whose changed-file set contains README.md but not README-zh-CN.md, re-derived and re-verified by the leg on every run. entries may only be REMOVED: a new violation fails until it is registered through --write, which is the moment a human looks at it. Forward-only - history is never rewritten to satisfy this rule.',
    generated_by: 'scripts/build-readme-pairing-baseline.js',
    generated_at: o.now || new Date().toISOString(),
    source_adr: 'docs/adr/0092-public-object-equivalence-and-post-land-verification-contract.md',
    anchor: live.anchor,
    anchor_subject: 'the commit that introduced ADR-0079 - the forward-only registration point of the pairing discipline',
    scanned_commits: live.scanned,
    entries: live.violations.map(function (v) {
      return { sha: v.sha, subject: v.subject };
    }),
  };
}

function stableCopy(m) {
  const c = JSON.parse(JSON.stringify(m));
  delete c.generated_at;
  delete c.scanned_commits; // range size drifts with unrelated commits
  return c;
}

function firstDiffPath(a, b, prefix) {
  const keys = Array.from(new Set(Object.keys(a).concat(Object.keys(b)))).sort();
  for (const k of keys) {
    const va = a[k], vb = b[k];
    if (JSON.stringify(va) !== JSON.stringify(vb)) {
      if (typeof va === 'object' && va && typeof vb === 'object' && vb) {
        const sub = firstDiffPath(va, vb, prefix ? prefix + '.' + k : k);
        if (sub) return sub;
      }
      return prefix ? prefix + '.' + k : k;
    }
  }
  return null;
}

function main(argv) {
  const check = argv.indexOf('--check') !== -1;
  const write = argv.indexOf('--write') !== -1;
  requireCapabilities('readme-pairing');
  const outAbs = path.join(ROOT, OUT_REL.split('/').join(path.sep));
  if (check) {
    // The leg's own reconcile is the authority (it also re-verifies every
    // entry); the generator adds drift detection on the file as a whole.
    const rec = pairing.reconcile(ROOT, {});
    for (const e of rec.errors) console.error('FAIL: ' + e);
    let committed = null;
    try { committed = JSON.parse(fs.readFileSync(outAbs, 'utf8')); } catch (e) {
      console.error('FAIL: ' + OUT_REL + ' unreadable - run: node scripts/build-readme-pairing-baseline.js --write');
      process.exit(1);
    }
    const regen = build(ROOT, {});
    regen.generated_at = committed.generated_at;
    const d = firstDiffPath(stableCopy(committed), stableCopy(regen));
    if (d) {
      console.error('FAIL: baseline drift at ' + d + ' - run: node scripts/build-readme-pairing-baseline.js --write');
      process.exit(1);
    }
    if (rec.errors.length) process.exit(1);
    console.log('[readme-pairing] OK: ' + rec.live.violations.length + ' registered unpaired commit(s) over ' + rec.live.scanned + ' scanned; baseline reconciled (ratchet holds)');
    process.exit(0);
  }
  if (!write) {
    console.error('FAIL: pass --write (regenerate the committed baseline) or --check (reconcile it)');
    process.exit(1);
  }
  const b = build(ROOT, {});
  fs.mkdirSync(path.dirname(outAbs), { recursive: true });
  fs.writeFileSync(outAbs, JSON.stringify(b, null, 2) + '\n', 'utf8');
  console.log('[readme-pairing] wrote ' + OUT_REL + ' (' + b.entries.length + ' registered unpaired commit(s) over ' + b.scanned_commits + ' scanned)');
  process.exit(0);
}

if (require.main === module) main(process.argv.slice(2));

module.exports = { build, stableCopy, firstDiffPath, OUT_REL };
